#!/usr/bin/env python3
"""Generate everything the book computes from data/.

Single sources of truth: data/chapters.tsv (the sequence) and the book's own tables
(week.tsv: doby w szablonach, breads.tsv: receptury).
Written to generated/ (COMMITTED, so a changed number shows in review and CI fails on drift):
  generated/structure.tex   \\part / \\input sequence for main.tex
  generated/meta.tex        chapter titles and lead lines as \\csdef macros
  generated/values.tex      every count the book prints, as \\gval keys
  generated/week-templates.tex  szablony doby (każdy MUSI sumować się do 24 h)
  generated/recipes.tex, recipe-timing.tex  receptury z procentami piekarskimi liczonymi z gramów
Usage: python3 tools/gen.py [--check]   Stdlib only.
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GEN = ROOT / "generated"
CHECK = "--check" in sys.argv
PARTIAL = "--partial" in sys.argv
SPECIAL = {"&": r"\&", "%": r"\%", "#": r"\#", "_": r"\_", "$": r"\$"}

def tex(s):
    return "".join(SPECIAL.get(c, c) for c in s).replace("~", r"\textasciitilde{}")

def read_tsv(name):
    lines = (ROOT / "data" / name).read_text(encoding="utf-8").splitlines()
    return [ln.split("\t") for ln in lines[1:] if ln.strip() and not ln.startswith("#")]

def fmt(x, nd=1):
    s = f"{x:.{nd}f}".replace(".", ",")
    return s.rstrip("0").rstrip(",") if "," in s else s

out = {}
chapters = read_tsv("chapters.tsv")
written = {p.name for p in (ROOT / "chapters").glob("c*.tex")}
vals = {}

# ---- structure and meta ---------------------------------------------------
st, meta, part = [], [], None
for n, short, partname, slug, lead in chapters:
    nn = f"{int(n):02d}"
    fn = f"c{nn}-{slug}"
    meta.append(f"\\csgdef{{chtitle@{nn}}}{{{tex(short)}}}\n\\csgdef{{chlead@{nn}}}{{{tex(lead)}}}")
    if partname != part:
        st.append(f"\\part{{{tex(partname)}}}"); part = partname
    if f"{fn}.tex" in written or not PARTIAL:
        st.append(f"\\input{{chapters/{fn}}}")
out["structure.tex"] = "% GENERATED by tools/gen.py -- do not edit\n" + "\n".join(st) + "\n"
out["meta.tex"] = "% GENERATED by tools/gen.py -- do not edit\n" + "\n".join(meta) + "\n"

# ---- counts from the sources ---------------------------------------------
def strip_comments(s): return re.sub(r"(?<!\\)%.*", "", s)
ex = tasks = traps = verify = 0
wr = 0
for p in sorted((ROOT / "chapters").glob("c*.tex")):
    s = strip_comments(p.read_text(encoding="utf-8"))
    wr += 1
    ex += len(re.findall(r"\\exitem\{", s)); tasks += len(re.findall(r"\\zadanie\{", s))
    traps += len(re.findall(r"\\begin\{falle\}", s)); verify += len(re.findall(r"\\verify\{", s))
for sub in ("frontmatter", "appendices"):
    for p in sorted((ROOT / sub).glob("*.tex")):
        verify += len(re.findall(r"\\verify\{", strip_comments(p.read_text(encoding="utf-8"))))
vals.update({"chapters.total": len(chapters), "written.total": wr, "exercises.total": ex,
             "tasks.total": tasks, "traps.total": traps, "verify.total": verify})

# ---- week templates: every template must sum to 24 hours ------------------
weeks = read_tsv("week.tsv")
tmpl = {}
for t, name, block, hours in weeks:
    tmpl.setdefault((t, name), []).append((block, float(hours)))
rows = []
for (t, name), blocks in tmpl.items():
    total = sum(h for _, h in blocks)
    if abs(total - 24.0) > 1e-9:
        sys.exit(f"week.tsv: template {t} ({name}) sums to {total}, not 24")
    sleep = sum(h for b, h in blocks if b.lower().startswith("sen"))
    free = sum(h for b, h in blocks if b.lower().startswith("wolne"))
    vals[f"week.{t}.sleep"] = fmt(sleep, 2); vals[f"week.{t}.free"] = fmt(free, 2)
    rows.append((t, name, blocks))
body = []
for t, name, blocks in rows:
    body.append(f"\\subsection*{{Szablon {t}: {tex(name)}}}\n\\begin{{center}}\\small\n\\begin{{tabular}}{{@{{}}lr@{{}}}}\\toprule\n"
                "\\textsf{\\textbf{Blok}} & \\textsf{\\textbf{Godziny}}\\\\\\midrule")
    for b, h in blocks: body.append(f"{tex(b)} & {fmt(h,2)}\\\\")
    body.append(f"\\midrule\\textbf{{Razem}} & \\textbf{{{fmt(sum(h for _, h in blocks),2)}}}\\\\\\bottomrule\n\\end{{tabular}}\n\\end{{center}}")
out["week-templates.tex"] = "% GENERATED by tools/gen.py -- do not edit\n" + "\n".join(body) + "\n"
vals["week.templates"] = len(rows)

# ---- recipes: baker's percentages COMPUTED from grams ----------------------
rec = read_tsv("breads.tsv")
body = ["\\begin{center}\\small\\begin{longtable}{@{}p{0.27\\linewidth}rrrrrr@{}}\\toprule",
        "\\textsf{\\textbf{Chleb}}&\\textsf{\\textbf{mąka g}}&\\textsf{\\textbf{woda g}}&\\textsf{\\textbf{sól g}}&\\textsf{\\textbf{zakwas/drożdże g}}&\\textsf{\\textbf{nawodnienie \\%}}&\\textsf{\\textbf{masa g}}\\\\\\midrule\\endhead\\bottomrule\\endlastfoot"]
timing = ["\\begin{center}\\small\\begin{longtable}{@{}p{0.27\\linewidth}rrrr@{}}\\toprule",
        "\\textsf{\\textbf{Chleb}}&\\textsf{\\textbf{zimno h}}&\\textsf{\\textbf{pokojowa h}}&\\textsf{\\textbf{piec °C}}&\\textsf{\\textbf{pieczenie min}}\\\\\\midrule\\endhead\\bottomrule\\endlastfoot"]
hyd_all = []
for i, (name, flour, water, salt, starter, yeast, cold, room, mins, temp) in enumerate(rec, 1):
    flour, water, salt, starter, yeast = map(float, (flour, water, salt, starter, yeast))
    tf = flour + starter / 2; tw = water + starter / 2          # starter is 100% hydration
    hyd = 100 * tw / tf; total = flour + water + salt + starter + yeast
    hyd_all.append(hyd)
    vals[f"bread.{i}.hydration"] = fmt(hyd, 1); vals[f"bread.{i}.mass"] = fmt(total, 0)
    leav = f"{fmt(starter,0)}" if starter else f"{fmt(yeast,1)}"
    body.append(f"{tex(name)}&{fmt(flour,0)}&{fmt(water,0)}&{fmt(salt,0)}&{leav}&{fmt(hyd,1)}&{fmt(total,0)}\\\\")
    timing.append(f"{tex(name)}&{cold}&{room}&{temp}&{mins}\\\\")
body.append("\\end{longtable}\\end{center}"); timing.append("\\end{longtable}\\end{center}")
out["recipes.tex"] = "% GENERATED by tools/gen.py -- do not edit\n" + "\n".join(body) + "\n"
out["recipe-timing.tex"] = "% GENERATED by tools/gen.py -- do not edit\n" + "\n".join(timing) + "\n"
vals["breads.total"] = len(rec)
vals["bread.hydration.min"] = fmt(min(hyd_all), 1); vals["bread.hydration.max"] = fmt(max(hyd_all), 1)


out["values.tex"] = "% GENERATED by tools/gen.py -- do not edit\n" + "\n".join(
    f"\\csgdef{{gval@{k}}}{{{v}}}" for k, v in sorted(vals.items())) + "\n"

stale = []
GEN.mkdir(exist_ok=True)
for name, text in out.items():
    p = GEN / name
    if CHECK:
        if not p.exists() or p.read_text(encoding="utf-8") != text: stale.append(name)
    else:
        p.write_text(text, encoding="utf-8")
if CHECK:
    if stale:
        print("STALE: " + ", ".join(stale) + "  -- run python3 tools/gen.py and commit"); sys.exit(1)
    print(f"gen --check: {len(out)} generated files current")
else:
    print(f"gen: wrote {len(out)} files")
